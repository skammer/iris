import { build } from "esbuild";
import postcss from "postcss";
import { readFile, writeFile } from "node:fs/promises";
const check = process.argv.includes("--check");
const app = postcss.parse(await readFile("frontend/styles/app.css", "utf8"));
app.walkAtRules("import", rule => {
  if (rule.params.includes("catalog.css")) throw new Error("Catalogue CSS must remain a separate entry point");
});
for (const [input, output] of [
  ["frontend/js/main.js", "public/web-components.js"],
  ["frontend/styles/app.css", "public/app.css"],
  ["frontend/styles/catalog.css", "public/catalog.css"],
]) {
  const result = await build({
    entryPoints: [input], outfile: output, bundle: true, write: false,
    format: "esm", target: "es2022", external: ["/public/*"],
    banner: input.endsWith(".js") ? { js: "// Generated by npm run build:ui; edit frontend/js instead." }
      : { css: "/* Generated by npm run build:ui; edit frontend/styles instead. */" },
  });
  for (const file of result.outputFiles) {
    if (check) {
      if (!Buffer.from(file.contents).equals(await readFile(file.path))) {
        throw new Error(`Stale generated asset: ${output}. Run npm run build:ui.`);
      }
    } else await writeFile(file.path, file.contents);
  }
}
